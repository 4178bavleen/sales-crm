// Seed rows, kept compact as
// [title, description, assignedTo, priority, status, dueAt, completedAt,
//  completedBy, completionNote, cancelReason, lead, deal, customer, company,
//  meeting, createdAt].
//
// Tasks mirror the backend `tasks` table. Note the schema's rule:
// completedAt/completedBy/completionNote are only populated for COMPLETED
// tasks, and cancelReason only for CANCELLED ones — everything else carries
// neither. `meeting` is left empty throughout because no meetings exist yet.
//
// `dueDate()` is computed against today so the Overdue / Due today / Upcoming
// filters always have something to show, whatever day this is opened.
function shiftDate(days: number): string {
  const date = new Date();
  date.setDate(date.getDate() + days);
  return date.toISOString().slice(0, 10);
}

