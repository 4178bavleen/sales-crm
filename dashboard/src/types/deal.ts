/** Look up a stage row by name (Deal.stageId -> PipelineStage.name). */
export function stageKindByName(
  name: string,
  rows: PipelineStageSeedRow[] = PIPELINE_STAGE_ROWS,
): StageKind {
  return rows.find(([stageName]) => stageName === name)?.[1] ?? "OPEN";
}

/**
 * The DealStatus implied by a stage's StageKind.
 * This is the link between the two columns: StageKind is what decides whether
 * a stage means an open, won, or lost deal.
 */
export function statusForStageKind(kind: StageKind): DealStatus {
  return kind === "WON" ? "WON" : kind === "LOST" ? "LOST" : "OPEN";
}
