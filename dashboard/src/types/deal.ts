// Domain types for the Deals & Pipeline feature.
// Mirrors the backend Prisma `Deal` model (backend/prisma/schema.prisma).
//
// API boundary notes (for when the deals API is wired up):
//   name             -> Deal.name
//   customer / lead  -> Deal.customerId / Deal.leadId (sent as names)
//   owner            -> Deal.ownerId        (lookup in users)
//   createdBy        -> Deal.createdById    (set server-side from the session)
//   product          -> Deal.productServiceId (lookup in products_services)
//   stage            -> Deal.stageId        (lookup in pipeline_stages)
//   status           -> DealStatus          (OPEN | WON | LOST)
//   estimatedValue   -> Deal.estimatedValue (pipeline value, NOT revenue)
//   wonRevenue / closedAt  -> only meaningful when status = WON
//   lostReason / lostNote  -> only meaningful when status = LOST
//   id/createdAt/updatedAt -> generated by the database

/** Prisma enum DealStatus. Kept separate from LeadStatus. */
export type DealStatus = "OPEN" | "WON" | "LOST";

/** Prisma enum StageKind — a stage is an open, won, or lost column. */
export type StageKind = "OPEN" | "WON" | "LOST";

export type Deal = {
  id: number;
  /** Deal.name */
  name: string;
  /** Resolved from Deal.customerId -> Company.name (via Customer). */
  customer: string;
  /** Resolved from Deal.leadId -> Lead name. Optional: not every deal came from a lead. */
  lead: string;
  /** Resolved from Deal.ownerId -> User.name. */
  owner: string;
  /** Resolved from Deal.productServiceId -> ProductService.name. */
  product: string;
  /** Resolved from Deal.stageId -> PipelineStage.name. */
  stage: string;
  status: DealStatus;
  /** Deal.estimatedValue — pipeline value, not revenue. */
  estimatedValue: number;
  /** Deal.expectedCloseDate (ISO date). */
  expectedCloseDate: string;
  /** Deal.nextAction — the agreed next step. */
  nextAction: string;
  /**
   * Deal.closedRevenue — only set when status = WON, per the schema comment
   * ("closed revenue - only set when the agreed business rule is met").
   */
  wonRevenue: number;
  /** Deal.closedAt (ISO date) — only set when status = WON. */
  closedAt: string;
  /** Resolved from Deal.lostReasonId -> Reason.name. Only set when status = LOST. */
  lostReason: string;
  /** Deal.lostNote — only set when status = LOST. */
  lostNote: string;
  /** ISO date strings (Deal.createdAt / updatedAt). */
  createdAt: string;
  updatedAt: string;
};

/** A pipeline stage row (PipelineStage model) — a Kanban board column. */
export type PipelineStage = {
  id: number;
  name: string;
  position: number;
  kind: StageKind;
};

/**
 * A row in the `pipeline_stages` table, kept compact as [name, kind].
 * `position` is the array index, so column order is the declaration order.
 */
export type PipelineStageSeedRow = [string, StageKind];

/** Fields the create/edit form collects. */
export type DealFormValues = {
  name: string;
  customer: string;
  lead: string;
  owner: string;
  product: string;
  stage: string;
  status: DealStatus;
  estimatedValue: string;
  expectedCloseDate: string;
  nextAction: string;
  wonRevenue: string;
  closedAt: string;
  lostReason: string;
  lostNote: string;
};

