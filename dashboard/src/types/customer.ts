// Domain types for the Customers feature.
// Mirrors the backend Prisma `Customer` model (backend/prisma/schema.prisma).
//
// IMPORTANT: unlike Contact/Company, a Customer has NO descriptive fields of its
// own. It is a conversion record — the junction between a Company, a Contact,
// and a User (owner). Everything a customer "looks like" is resolved from those
// relations, which the API returns nested:
//
//   company / primaryContact / owner -> resolved names from the related rows
//   convertedAt                      -> Customer.convertedAt
//   notes                            -> Customer.notes
//   id/createdAt/updatedAt           -> generated by the database
//
// Deal metrics are aggregated from the related Deal[] relation
// (Customer.deals -> Deal.customerId), not stored on the customer row.

export type Customer = {
  id: number;
  companyId?: number | null;
  primaryContactId?: number | null;
  ownerId?: number | null;
  /**
   * Resolved from Customer.companyId -> Company.name.
   * This is the customer's row title, since the schema has no name of its own.
   */
  company: string;
  /** Company.industry, shown alongside the company name. */
  industry: string;
  /** Resolved from Customer.primaryContactId -> Contact.fullName. */
  primaryContact: string;
  /** Resolved from Customer.ownerId -> User.name. */
  owner: string;
  notes: string;
  /**
   * Number of related deals. On the API this is `Customer._count.deals`;
   * here it is derived from the seeded deals (matching customerId).
   */
  dealCount: number;
  /**
   * Sum of Deal.estimatedValue across this customer's deals (pipeline, not
   * revenue). On the API this is an aggregate over `Customer.deals`.
   */
  pipelineValue: number;
  /** Customer.convertedAt — when the source lead was converted. */
  convertedAt: string;
  /** ISO date strings (Customer.createdAt / updatedAt). */
  createdAt: string;
  updatedAt: string;
  companyDetails?: {
    id: number;
    name: string;
    industry?: string | null;
    website?: string | null;
    phone?: string | null;
    city?: string | null;
    country?: string | null;
  } | null;
  contactDetails?: {
    id: number;
    fullName: string;
    email?: string | null;
    phone?: string | null;
    jobTitle?: string | null;
  } | null;
  ownerDetails?: {
    id: number;
    name: string;
    email: string;
  } | null;
};

/**
 * Fields the conversion form collects.
 * Maps to Customer.companyId / primaryContactId / ownerId / notes / convertedAt.
 * `company` and `primaryContact` are sent as names at the API boundary.
 */
export type CustomerFormValues = {
  companyId?: number | null;
  primaryContactId?: number | null;
  ownerId?: number | null;
  company: string;
  primaryContact: string;
  owner: string;
  convertedAt: string;
  notes: string;
};

